"""
CubeAI - Cubie Converter

Converts between:
    CubeState  (sticker grid)
    CubieState (physical piece + orientation)

Design
------
* Single source of truth for every constant.
  cubeState.py    -> FACE_TO_COLOR, FACE_NAMES, CubeState
  cubie.py        -> CornerCubie, EdgeCubie, CubieState
  cubeValidator   -> CORNER_FACELETS, EDGE_FACELETS,
                     CORNER_COLORS (frozensets), EDGE_COLORS (frozensets)
  move.py         -> apply_algorithm, apply_algorithm_cubie, invert_algorithm

* Orientation convention is an exact mirror of CubeValidator.
  _corner_orientation / _edge_orientation are copied verbatim.

* CORNER_PERM_TABLE drives cubiestate_to_cubestate reconstruction.
  Generated by BFS over all reachable cube states; zero conflicts.
  Key: (piece_is_D_layer, slot_is_D_layer, orientation)

* CORNER_FACELET_CANONICAL — the correct canonical tuple for each corner
  PIECE is derived directly from the face geometry (CORNER_FACELETS),
  NOT from cubie.py CORNER_COLORS whose UFR entry uses a different
  sticker ordering.  All other slots agree, but relying on geometry
  makes the code robust to any future ordering changes.

* EDGE_FACELET_CANONICAL — similarly derived from EDGE_FACELETS.

Color scheme (fixed in cubeState.py / cubeValidator.py):

    U=white  R=red    F=green  D=yellow  L=orange  B=blue

Corner slot order (cubeValidator CORNER_FACELETS):

    0 UFR  1 URB  2 UBL  3 ULF
    4 DFR  5 DRB  6 DBL  7 DLF

Edge slot order (cubeValidator EDGE_FACELETS):

     0 UF   1 UR   2 UB   3 UL
     4 FR   5 BR   6 BL   7 FL
     8 DF   9 DR  10 DB  11 DL

Pipeline:

    Scanner -> CubeState -> cubieConverter -> CubieState -> Solver
"""

