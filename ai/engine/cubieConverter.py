_ALGORITHMS: tuple[str, ...] = (
    "R", "U", "F", "D", "L", "B",
    "R U R' U'",
    "R U R' U' F2 L D",
    "R U R' U' F2 L D B R2 U2",
    "F R U R' U' F'",
    "R2 U2 F2 D2 L2 B2",
)

def _test_solved_cubestate_to_cubiestate() -> bool:
    cube   = _create_solved_cubestate()
    cubie  = cubestate_to_cubiestate(cube)
    solved = _create_solved_cubiestate()
    passed = _cubiestate_equal(cubie, solved)
    print("  Solved CubeState -> CubieState:", "PASS" if passed else "FAIL")
    return passed

def _test_solved_cubiestate_to_cubestate() -> bool:
    cubie  = _create_solved_cubiestate()
    cube   = cubiestate_to_cubestate(cubie)
    solved = _create_solved_cubestate()
    passed = _cubestate_equal(cube, solved)
    print("  Solved CubieState -> CubeState:", "PASS" if passed else "FAIL")
    return passed

def _test_round_trips() -> bool:
    if _move_module is None:
        print("  Round-trip tests skipped: move.py not available.")
        return True
    solved = _create_solved_cubestate()
    all_passed = True
    print("  Round-trip tests (CubeState -> CubieState -> CubeState):")
    for alg in _ALGORITHMS:
        try:
            scrambled = _move_module.apply_algorithm(solved, alg)
            converted = cubestate_to_cubiestate(scrambled)
            restored  = cubiestate_to_cubestate(converted)
            passed    = _cubestate_equal(scrambled, restored)
        except Exception as exc:
            print(f"    {alg}: FAIL ({exc})")
            all_passed = False
            continue
        print(f"    {alg}:", "PASS" if passed else "FAIL")
        if not passed: all_passed = False
    return all_passed

def _test_consistency() -> bool:
    if _move_module is None:
        print("  Consistency tests skipped: move.py not available.")
        return True
    solved_cube  = _create_solved_cubestate()
    solved_cubie = _create_solved_cubiestate()
    all_passed   = True
    print("  Consistency tests (CubeState move == CubieState move via converter):")
    for alg in _ALGORITHMS:
        try:
            moved_cube     = _move_module.apply_algorithm(solved_cube, alg)
            cubie_via_cube = cubestate_to_cubiestate(moved_cube)
            cubie_direct   = _move_module.apply_algorithm_cubie(solved_cubie, alg)
            passed         = _cubiestate_equal(cubie_via_cube, cubie_direct)
        except Exception as exc:
            print(f"    {alg}: FAIL ({exc})")
            all_passed = False
            continue
        print(f"    {alg}:", "PASS" if passed else "FAIL")
        if not passed: all_passed = False
    return all_passed

def _test_inverse_round_trip() -> bool:
    if _move_module is None:
        print("  Inverse round-trip tests skipped: move.py not available.")
        return True
    solved = _create_solved_cubestate()
    all_passed = True
    print("  Inverse round-trip tests (scramble + inverse -> solved):")
    for alg in _ALGORITHMS:
        try:
            inverse   = _move_module.invert_algorithm(alg)
            scrambled = _move_module.apply_algorithm(solved, alg)
            cubie_sc  = cubestate_to_cubiestate(scrambled)
            cubie_res = _move_module.apply_algorithm_cubie(cubie_sc, inverse)
            restored  = cubiestate_to_cubestate(cubie_res)
            passed    = _cubestate_equal(solved, restored)
        except Exception as exc:
            print(f"    {alg}: FAIL ({exc})")
            all_passed = False
            continue
        print(f"    {alg}:", "PASS" if passed else "FAIL")
        if not passed: all_passed = False
    return all_passed

def _test_immutability() -> bool:
    cube_orig  = _create_solved_cubestate()
    cubie_orig = _create_solved_cubiestate()
    cube_snap  = _create_solved_cubestate()
    cubie_snap = _create_solved_cubiestate()
    cubestate_to_cubiestate(cube_orig)
    cubiestate_to_cubestate(cubie_orig)
    cube_ok  = _cubestate_equal(cube_orig, cube_snap)
    cubie_ok = _cubiestate_equal(cubie_orig, cubie_snap)
    print("  CubeState unchanged after conversion:",  cube_ok)
    print("  CubieState unchanged after conversion:", cubie_ok)
    return cube_ok and cubie_ok

def _test_validation() -> bool:
    if _move_module is None:
        print("  Validation tests skipped: move.py not available.")
        return True
    solved = _create_solved_cubestate()
    all_passed = True
    print("  Validation tests (converted CubieState passes cubie.py validate()):")
    for alg in _ALGORITHMS:
        try:
            scrambled = _move_module.apply_algorithm(solved, alg)
            cubie_sc  = cubestate_to_cubiestate(scrambled)
            result    = cubie_sc.validate()
            passed    = result.get("valid", False)
        except Exception as exc:
            print(f"    {alg}: FAIL ({exc})")
            all_passed = False
            continue
        errs   = [] if passed else result.get("errors", [])
        suffix = "" if passed else f" ({', '.join(errs)})"
        print(f"    {alg}:", ("PASS" if passed else "FAIL") + suffix)
        if not passed: all_passed = False
    return all_passed


