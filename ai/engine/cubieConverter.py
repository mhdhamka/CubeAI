def _create_solved_cubestate() -> "CubeState":
    if _CubeState is None:
        raise RuntimeError(CUBE_STATE_IMPORT_ERROR)
    return _CubeState({
        face: [[color] * 3 for _ in range(3)]
        for face, color in _FACE_TO_COLOR.items()
    })

def _create_solved_cubiestate() -> "CubieState":
    if _CubieState is None:
        raise RuntimeError(CUBIE_IMPORT_ERROR)
    return _CubieState()

def _cubiestate_equal(a: "CubieState", b: "CubieState") -> bool:
    for i in range(8):
        if a.corners[i].piece       != b.corners[i].piece:       return False
        if a.corners[i].orientation != b.corners[i].orientation: return False
    for i in range(12):
        if a.edges[i].piece         != b.edges[i].piece:         return False
        if a.edges[i].orientation   != b.edges[i].orientation:   return False
    return True

def _cubestate_equal(a: "CubeState", b: "CubeState") -> bool:
    for face in _FACE_NAMES:
        for row in range(3):
            for col in range(3):
                if a.faces[face][row][col] != b.faces[face][row][col]:
                    return False
    return True


