def _build_corner_canonical() -> tuple[tuple[str, str, str], ...]:
    if CORNER_FACELETS is None:
        return (
            ("white",  "green",  "red"),
            ("white",  "red",    "blue"),
            ("white",  "blue",   "orange"),
            ("white",  "orange", "green"),
            ("yellow", "green",  "red"),
            ("yellow", "red",    "blue"),
            ("yellow", "blue",   "orange"),
            ("yellow", "orange", "green"),
        )
    return tuple(
        tuple(_FACE_TO_COLOR[face] for face, _, _ in facelets)   # type: ignore[misc]
        for facelets in CORNER_FACELETS
    )

def _build_edge_canonical() -> tuple[tuple[str, str], ...]:
    if EDGE_FACELETS is None:
        return (
            ("white",  "green"),  ("white",  "red"),
            ("white",  "blue"),   ("white",  "orange"),
            ("green",  "red"),    ("blue",   "red"),
            ("blue",   "orange"), ("green",  "orange"),
            ("yellow", "green"),  ("yellow", "red"),
            ("yellow", "blue"),   ("yellow", "orange"),
        )
    return tuple(
        tuple(_FACE_TO_COLOR[face] for face, _, _ in facelets)   # type: ignore[misc]
        for facelets in EDGE_FACELETS
    )

CORNER_PIECE_CANONICAL: tuple[tuple[str, str, str], ...] = _build_corner_canonical()
EDGE_PIECE_CANONICAL:   tuple[tuple[str, str], ...]      = _build_edge_canonical()


# ===========================================================================
# Pre-computed O(1) Lookup Dictionaries
# ===========================================================================

def _build_lookups() -> tuple[dict[frozenset[str], int], dict[frozenset[str], int]]:
    corner_lookup = {}
    edge_lookup = {}
    if VAL_CORNER_COLORS is not None:
        for idx, colors in enumerate(VAL_CORNER_COLORS):
            corner_lookup[frozenset(colors)] = idx
    if VAL_EDGE_COLORS is not None:
        for idx, colors in enumerate(VAL_EDGE_COLORS):
            edge_lookup[frozenset(colors)] = idx
    return corner_lookup, edge_lookup

_CORNER_LOOKUP, _EDGE_LOOKUP = _build_lookups()


# ===========================================================================
# Corner reconstruction permutation table
# ===========================================================================

CORNER_PERM_TABLE: dict[tuple[bool, bool, int], tuple[int, int, int]] = {
    (False, False, 0): (0, 1, 2),
    (False, False, 1): (2, 0, 1),
    (False, False, 2): (1, 2, 0),
    (False, True,  0): (0, 2, 1),
    (False, True,  1): (2, 1, 0),
    (False, True,  2): (1, 0, 2),
    (True,  False, 0): (0, 2, 1),
    (True,  False, 1): (1, 0, 2),
    (True,  False, 2): (2, 1, 0),
    (True,  True,  0): (0, 1, 2),
    (True,  True,  1): (1, 2, 0),
    (True,  True,  2): (2, 0, 1),
}


