# ===========================================================================
# Orientation helpers — Robust handling for single face rotations
# ===========================================================================

def _corner_orientation(colors: list[str], facelets: Any) -> int:
    """
    Computes corner orientation (0, 1, or 2).
    Determined by finding where the U/D primary color lands on the facelet structure.
    """
    ud_index = next(
        (i for i, c in enumerate(colors) if c in ("white", "yellow")), -1
    )
    if ud_index == -1:
        return 0
    
    # U- and D-layer facelet definitions have opposite handedness.
    if facelets[0][0] == "U":
        return ud_index
    return (-ud_index) % 3


def _edge_orientation(colors: list[str], facelets: Any) -> int:
    """
    Computes edge orientation (0 or 1) from the cubie's canonical sticker order.

    This is the convention used by the cubie move engine: U/D/R/L turns
    preserve the canonical order and F/B turns reverse it.
    """
    piece_idx = _EDGE_LOOKUP.get(frozenset(colors))
    if piece_idx is None:
        return 0
    return 0 if tuple(colors) == EDGE_PIECE_CANONICAL[piece_idx] else 1


# ===========================================================================
# CubeState → CubieState
# ===========================================================================

def cubestate_to_cubiestate(cube: "CubeState") -> "CubieState":
    """
    Convert a CubeState (sticker grid) to a CubieState (piece + orientation).
    Performs O(1) lookups and validates topological consistency via CubeValidator.
    """
    _require_imports()

    # Rebuild lookups dynamically if they were uninitialized at module load time
    global _CORNER_LOOKUP, _EDGE_LOOKUP
    if not _CORNER_LOOKUP and VAL_CORNER_COLORS is not None:
        _CORNER_LOOKUP, _EDGE_LOOKUP = _build_lookups()

    # Optional deep topological validation using CubeValidator (handles objects and dicts)
    validator = _CubeValidator()
    if hasattr(validator, "validate"):
        validation_res = validator.validate(cube)
        is_valid = True
        errors = []
        
        if isinstance(validation_res, dict):
            is_valid = validation_res.get("valid", True)
            errors = validation_res.get("errors", [])
        else:
            is_valid = getattr(validation_res, "valid", True)
            errors = getattr(validation_res, "errors", [])

        if not is_valid:
            raise ValueError(f"Invalid CubeState topology: {errors}")

    corners: list[Any] = []
    for slot_idx, facelets in enumerate(CORNER_FACELETS):
        colors: list[str] = [
            str(cube.faces[face][row][col]).lower()
            for face, row, col in facelets
        ]
        color_set = frozenset(colors)
        if color_set not in _CORNER_LOOKUP:
            raise ValueError(
                f"Unrecognized corner piece at slot {slot_idx} with colors {colors} (set: {color_set})"
            )
        piece_idx  = _CORNER_LOOKUP[color_set]
        orientation = _corner_orientation(colors, facelets)
        corners.append(_CornerCubie(piece=piece_idx, orientation=orientation))

    edges: list[Any] = []
    for slot_idx, facelets in enumerate(EDGE_FACELETS):
        colors = [
            str(cube.faces[face][row][col]).lower()
            for face, row, col in facelets
        ]
        color_set = frozenset(colors)
        if color_set not in _EDGE_LOOKUP:
            raise ValueError(
                f"Unrecognized edge piece at slot {slot_idx} with colors {colors} (set: {color_set})"
            )
        piece_idx  = _EDGE_LOOKUP[color_set]
        orientation = _edge_orientation(colors, facelets)
        edges.append(_EdgeCubie(piece=piece_idx, orientation=orientation))

    return _CubieState(corners=corners, edges=edges)


# ===========================================================================
# CubieState → CubeState
# ===========================================================================

def cubiestate_to_cubestate(cubie: "CubieState") -> "CubeState":
    """
    Convert a CubieState (piece + orientation) to a CubeState (sticker grid).
    """
    _require_imports()

    faces: dict[str, list[list[str]]] = {
        face: [[""] * 3 for _ in range(3)] for face in _FACE_NAMES
    }
    for face, color in _FACE_TO_COLOR.items():
        faces[face][1][1] = color

    # ---- corners ----
    for slot_idx, facelets in enumerate(CORNER_FACELETS):
        corner      = cubie.corners[slot_idx]
        piece_idx   = corner.piece
        orientation = corner.orientation

        if orientation not in (0, 1, 2):
            raise ValueError(
                f"Corner slot {slot_idx}: invalid orientation {orientation}"
            )

        canonical  = CORNER_PIECE_CANONICAL[piece_idx]
        piece_is_d = piece_idx >= 4
        slot_is_d  = facelets[0][0] == "D"

        perm    = CORNER_PERM_TABLE[(piece_is_d, slot_is_d, orientation)]
        rotated = (canonical[perm[0]], canonical[perm[1]], canonical[perm[2]])

        for (face, row, col), color in zip(facelets, rotated):
            faces[face][row][col] = color

    # ---- edges ----
    for slot_idx, facelets in enumerate(EDGE_FACELETS):
        edge        = cubie.edges[slot_idx]
        piece_idx   = edge.piece
        orientation = edge.orientation

        if orientation not in (0, 1):
            raise ValueError(
                f"Edge slot {slot_idx}: invalid orientation {orientation}"
            )

        canonical_edge = EDGE_PIECE_CANONICAL[piece_idx]
        if orientation == 0:
            rotated_edge = canonical_edge
        else:
            rotated_edge = (canonical_edge[1], canonical_edge[0])

        for (face, row, col), color in zip(facelets, rotated_edge):
            faces[face][row][col] = color

    return _CubeState(faces)


